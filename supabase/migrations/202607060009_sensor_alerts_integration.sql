create or replace function public.convert_sensor_alert_to_report(
  p_alert_id bigint
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_alert public.sensor_alerts%rowtype;
  v_report_id bigint;
  v_tracking_code text;
  v_year text;
  v_urgency text;
  v_risk_score integer;
  v_risk_label text;
begin
  if auth.uid() is null then
    raise exception 'Authentication required' using errcode = '28000';
  end if;

  if not public.is_admin() then
    raise exception 'Admin role required' using errcode = '42501';
  end if;

  select * into v_alert
  from public.sensor_alerts
  where id = p_alert_id
  for update;

  if not found then
    raise exception 'Sensor alert not found' using errcode = 'P0002';
  end if;

  if v_alert.alert_status = 'Converted to Report' then
    raise exception 'Sensor alert has already been converted to a report' using errcode = 'P0001';
  end if;

  if v_alert.risk_level not in ('Warning', 'Critical') then
    raise exception 'Only Warning or Critical sensor alerts can be converted to reports' using errcode = 'P0001';
  end if;

  v_urgency := case
    when v_alert.risk_level = 'Critical' then 'Critical'
    else 'High'
  end;

  v_risk_label := case
    when v_alert.risk_level = 'Critical' then 'Critical'
    else 'High'
  end;

  v_risk_score := case
    when v_alert.risk_level = 'Critical' then 92
    else 76
  end;

  v_year := extract(year from now())::text;

  loop
    v_tracking_code := 'MKC-' || v_year || '-S' ||
      lpad((floor(random() * 900000) + 100000)::integer::text, 6, '0');
    exit when not exists (
      select 1 from public.reports
      where tracking_code = v_tracking_code
    );
  end loop;

  v_report_id := floor(extract(epoch from clock_timestamp()) * 1000)::bigint;

  while exists (
    select 1 from public.reports where id = v_report_id
  ) loop
    v_report_id := v_report_id + 1;
  end loop;

  insert into public.reports (
    id,
    tracking_code,
    issue_type,
    location_name,
    area,
    description,
    latitude,
    longitude,
    urgency,
    reporter_type,
    reporter_name,
    reporter_phone,
    reporter_email,
    is_anonymous,
    near_sensitive_area,
    risk_score,
    risk_label,
    status,
    created_at,
    photo_url
  )
  values (
    v_report_id,
    v_tracking_code,
    left(coalesce(nullif(v_alert.issue_type, ''), 'Flooding / Stagnant Water'), 120),
    left(coalesce(nullif(v_alert.location_name, ''), 'Sensor location'), 240),
    left(coalesce(nullif(v_alert.location_name, ''), 'Sensor location'), 240),
    left('[SENSOR] ' || coalesce(nullif(v_alert.explanation, ''), 'IoT sensor reading requires field verification.'), 2000),
    v_alert.latitude,
    v_alert.longitude,
    v_urgency,
    'IoT Sensor',
    '',
    '',
    '',
    true,
    'No',
    v_risk_score,
    v_risk_label,
    'Reported',
    now(),
    ''
  );

  insert into public.report_updates (
    report_id,
    status,
    note,
    updated_by,
    updated_by_name
  )
  values (
    v_report_id,
    'Reported',
    'Report created from sensor alert ' || v_alert.sensor_id || '.',
    auth.uid(),
    'Make Kenya Clean Sensor Ingestion'
  );

  update public.sensor_alerts
  set
    alert_status = 'Converted to Report',
    converted_report_id = v_report_id,
    converted_tracking_code = v_tracking_code,
    converted_at = now()
  where id = p_alert_id;

  return jsonb_build_object(
    'success', true,
    'alert_id', p_alert_id,
    'report_id', v_report_id,
    'tracking_code', v_tracking_code
  );
end;
$$;

