-- Live IoT sensor ingestion infrastructure for ESP32/HC-SR04 prototype.
--
-- This migration is additive and non-destructive. It creates locked-down
-- sensor tables, public-safe/admin-safe views, and an admin-only RPC for
-- converting Warning/Critical sensor alerts into standard reports.
--
-- Device token setup pattern for a physical sensor:
-- 1. Generate a one-time token outside the database:
--    openssl rand -hex 32
-- 2. Store only the hash:
--    insert into public.sensor_devices (
--      sensor_id,
--      sensor_name,
--      sensor_type,
--      issue_type,
--      location_name,
--      latitude,
--      longitude,
--      risk_direction,
--      token_hash,
--      token_last_four
--    )
--    values (
--      'DRAIN-KIB-001',
--      'Kibera Soweto East Drainage Sensor',
--      'Drainage Water Level',
--      'Flooding / Stagnant Water',
--      'Kibera Soweto East',
--      -1.3133,
--      36.7870,
--      'lower_is_risk',
--      encode(extensions.digest('mkc-sensor-token-v1:' || '<DEVICE_TOKEN>', 'sha256'), 'hex'),
--      right('<DEVICE_TOKEN>', 4)
--    );
-- 3. Put only <DEVICE_TOKEN> on the ESP32, never a Supabase service-role key.

